//! The multiples of each curve's base point that the fixed-base
//! scalar multiplication reads.
//!
//! The scalar is cut into six blocks, and four combs run side by
//! side over them, the comb `i` reading the bits `i` spans into each
//! block. Entry `j - 1` of comb `i`'s table is the sum, over the set
//! bits `b` of `j`, of `2^(b d + i s) G`, where `d` is the bits in a
//! block and `s` is `d` divided by the number of combs and rounded
//! up. One pass down the spans then costs `s` doublings and four
//! additions each, against a doubling and an addition for every bit
//! of a block with one comb, and four doublings and an addition for
//! every four bits of scalar with none.
//!
//! Coordinates are affine and already in the field's Montgomery
//! domain, so a lookup is a scan and nothing else. The tables are
//! generated by `print_base_tables`, and laid out by hand rather
//! than by `rustfmt`, which gives a limb a line. Every entry is
//! rebuilt from the generator and compared by
//! `base_tables_are_multiples_of_g`.


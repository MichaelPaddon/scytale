//! The multiples of each curve's base point that the fixed-base
//! scalar multiplication reads.
//!
//! The scalar is cut into six blocks, and entry `j - 1` is the sum
//! of the blocks' bases over the set bits of `j`: with `d` the bits
//! in a block, the base of block `i` is `2^(i * d) G`. One pass down
//! the blocks then costs `d` doublings and `d` additions, against an
//! addition and four doublings for every four bits of scalar.
